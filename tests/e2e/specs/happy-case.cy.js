/**
 * End-2-end HAPPY CASE test for liquido-mobile-pwa frontend.
 * This test runs through the easiest possible use case flow.
 * Only the successful "happy path" without any error cases or edge cases.
 * This test is completely standalone. It creates all the necessary test data along the way.
 * It does also not depend on any devLogin or workarounds. It tests the app completely as a black box form end user perspective.
 */

/*
 * A unique id per RUN, used to build every fixture below.
 *
 * This used to be `Date.now() % 100000`, which wraps every 100 seconds - two runs started ~100s
 * apart reused the same admin email, and team creation then died on a 401 that did not reproduce.
 * Full millisecond timestamp plus a random suffix: no wrap, no collision between parallel runs.
 */
const now = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`
console.log("Running Cypress HAPPY CASE test (run id=" + now + ")")

