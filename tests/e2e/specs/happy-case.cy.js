/*
 * Row selectors for the poll editor (poll-card-edit.vue).
 *
 * Every row carries data-row-state="editing|saved". A row for a proposal that already exists in the
 * backend also carries data-proposal-id; the trailing "add another proposal" row does not, because
 * it has no id yet. That distinction matters: opening an existing proposal for editing leaves TWO
 * rows in state "editing" - the one you opened, and the empty one at the bottom.
 */
const SAVED_ROW    = '[data-row-state="saved"]'                        // an existing proposal, read only
const OPENED_ROW   = '[data-proposal-id][data-row-state="editing"]'    // an existing proposal, opened for editing
const NEW_ROW      = '.proposal-row:not([data-proposal-id])'           // the empty "add another" row
	
/* When one of test steps fails, then abort the whole test run. */
afterEach(function() {
  if (this.currentTest.state === 'failed') {
		console.log("[ERROR] Cypress test step in happy case failed. Aborting.")
    Cypress.runner.stop()
  }
});

